def seed_core() -> dict[str, int]:
    SiteSettings.load()
    counts = {}
    if not Tariff.objects.exists():
        Tariff.objects.bulk_create([Tariff(order=i, **t) for i, t in enumerate(TARIFFS, 1)])
        counts["тарифы"] = len(TARIFFS)
    if not FAQItem.objects.exists():
        FAQItem.objects.bulk_create([FAQItem(question=q, answer=a, order=i) for i, (q, a) in enumerate(FAQ, 1)])
        counts["вопросы FAQ"] = len(FAQ)
    if not ContactChannel.objects.exists():
        ContactChannel.objects.bulk_create([ContactChannel(**c) for c in CHANNELS])
        counts["каналы связи"] = len(CHANNELS)
    if not Review.objects.exists():
        Review.objects.bulk_create([Review(**r) for r in EXAMPLE_REVIEWS])
        counts["отзывы-черновики"] = len(EXAMPLE_REVIEWS)
    return counts
